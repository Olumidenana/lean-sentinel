class VulnerableAiGeneratedAlgorithm(QCAlgorithm):
    """
    Example of an algorithm generated by an unconstrained LLM (Claude/GPT).
    Suffers from 6 real QuantConnect LEAN anti-patterns:
    - Missing explicit Resolution in AddEquity
    - SetWarmUp called without `if self.IsWarmingUp: return` guard in OnData
    - Indicator value accessed without checking `.IsReady`
    - Naked MarketOrder bypasses portfolio risk constraints
    - Direct subscript access on slice (`data["SPY"]`) without ContainsKey() check
    - Missing Risk Management Model
    """

    def Initialize(self):
        self.SetStartDate(2023, 1, 1)
        self.SetCash(100000)

        # Defect 1: Missing explicit Resolution argument
        self.AddEquity("SPY")

        # Indicator created
        self.sma = self.SMA("SPY", 50)

        # Defect 2: Warmup declared
        self.SetWarmUp(50)

    def OnData(self, data: Slice):
        # Defect 3: No warmup guard (missing `if self.IsWarmingUp: return`)

        # Defect 4: Direct key access without `data.ContainsKey("SPY")`
        spy_bar = data["SPY"]

        # Defect 5: Reading .Current.Value without `self.sma.IsReady` check
        sma_val = self.sma.Current.Value

        # Defect 6: Direct MarketOrder with hardcoded sizing
        if spy_bar.Close > sma_val:
            self.MarketOrder("SPY", 100)
        else:
            self.MarketOrder("SPY", -100)
